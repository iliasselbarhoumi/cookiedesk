#!/usr/bin/env python3
"""
Builds _locales/<lang>/messages.json from the flat i18n/<lang>.json files.

  python3 i18n/build_locales.py

Each i18n/<lang>.json is a flat {"key": "text"} map; positional substitutions are written
as $1, $2 … and turned into Chrome's named placeholders. The script fails if a language
is missing a key, has an extra key, uses different substitutions than English, or breaks
the Chrome Web Store limits for the name / summary.

It also writes src/lib/i18n-en.js, the English fallback that t() uses when chrome.i18n
returns nothing.

Plurals: key_one / key_other, picked at runtime with Intl.PluralRules ("one" or anything
else). A _one form may leave out the count ($1) where that language's "one" means exactly
1 (e.g. Arabic "نافذة واحدة"); _other must work for every other number, so languages with
few/many forms use count-neutral wording ("Windows: $1").
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '_locales')
EN_JS = os.path.join(HERE, '..', 'src', 'lib', 'i18n-en.js')
LIMITS = {'extension_name': 75, 'extension_description': 132}  # Chrome's manifest caps
SUB = re.compile(r'\$(\d)')


def to_chrome(text):
    """'Speed $1' -> ('Speed $P1$', {'p1': {'content': '$1'}})"""
    subs = sorted(set(SUB.findall(text)))
    msg = SUB.sub(lambda m: f'$P{m.group(1)}$', text)
    entry = {'message': msg}
    if subs:
        entry['placeholders'] = {f'p{n}': {'content': f'${n}'} for n in subs}
    return entry


def main():
    en = json.load(open(os.path.join(HERE, 'en.json'), encoding='utf-8'))
    langs = sorted(f[:-5] for f in os.listdir(HERE) if f.endswith('.json'))
    errors = []
    for lang in langs:
        data = json.load(open(os.path.join(HERE, f'{lang}.json'), encoding='utf-8'))
        missing = en.keys() - data.keys()
        extra = data.keys() - en.keys()
        if missing:
            errors.append(f'{lang}: missing {sorted(missing)}')
        if extra:
            errors.append(f'{lang}: extra {sorted(extra)}')
        for key, text in data.items():
            if key not in en:
                continue
            if not isinstance(text, str) or not text.strip():
                errors.append(f'{lang}.{key}: empty')
                continue
            subs, en_subs = set(SUB.findall(text)), set(SUB.findall(en[key]))
            if not (subs <= en_subs if key.endswith('_one') else subs == en_subs):
                errors.append(f'{lang}.{key}: substitutions differ from English')
            if key in LIMITS and len(text) > LIMITS[key]:
                errors.append(f'{lang}.{key}: {len(text)} chars > {LIMITS[key]}')
        if not missing:
            folder = os.path.join(OUT, lang)
            os.makedirs(folder, exist_ok=True)
            messages = {k: to_chrome(data[k]) for k in en}
            with open(os.path.join(folder, 'messages.json'), 'w', encoding='utf-8') as f:
                json.dump(messages, f, ensure_ascii=False, indent=2)
                f.write('\n')
    with open(EN_JS, 'w', encoding='utf-8') as f:
        f.write('// Generated by i18n/build_locales.py from i18n/en.json. Do not edit.\n')
        f.write('// English fallback for t() when chrome.i18n has no message (Node tests, or\n')
        f.write('// Chrome intermittently serving an empty catalog right after an install).\n')
        f.write('export default ' + json.dumps(en, ensure_ascii=False, indent=0) + ';\n')
    if errors:
        print('\n'.join(errors))
        sys.exit(1)
    print(f'Built {len(langs)} locales: {" ".join(langs)}')


if __name__ == '__main__':
    main()
